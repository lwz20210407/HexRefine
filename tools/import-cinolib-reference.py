"""Mechanical, pinned C++ initializer -> integer-grid TypeScript reference data.

Development-only importer; the generated native reference kernel needs no Python.
Usage: python -B tools/import-cinolib-reference.py HEADER LICENSE OUTPUT
"""
from pathlib import Path
from fractions import Fraction
import ast
import hashlib
import json
import re
import sys

COMMIT = '151dc5c46309affedadb9b45619cc137fb7326ed'
SHA256 = 'ef2df0d02b885e92bb497c98c5649e55b13808719f9895b8b89e6a31280476b5'


def initializer(body, name):
    match = re.search(r'\b' + name + r'\s*=\s*(\{)', body)
    if not match:
        raise ValueError('missing initializer: ' + name)
    start = match.start(1)
    depth = 0
    for end in range(start, len(body)):
        depth += body[end] == '{'
        depth -= body[end] == '}'
        if depth == 0:
            text = body[start:end + 1].replace('{', '[').replace('}', ']')
            text = re.sub(r'\btrue\b', 'True', text)
            return ast.literal_eval(re.sub(r'\bfalse\b', 'False', text))
    raise ValueError('unclosed initializer: ' + name)


def main():
    source, license_file, output = map(Path, sys.argv[1:])
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('unrecognized source revision; re-audit before updating')
    notice = license_file.read_text(encoding='utf-8').strip()
    if 'Copyright (c) 2016 Marco Livesu' not in notice or '*/' in notice:
        raise ValueError('invalid upstream license notice')
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', raw.decode(), flags=re.S)
    starts = list(re.finditer(r'\bnamespace\s+(\w+)\s*\{', text))
    schemes = {}
    for index, match in enumerate(starts):
        name = match.group(1)
        if name == 'cinolib':
            continue
        body = text[match.end():starts[index + 1].start() if index + 1 < len(starts) else len(text)]
        vertices = initializer(body, 'verts')
        coordinates = [Fraction(str(v)) * 20 for v in vertices]
        if len(coordinates) % 3 or any(v.denominator != 1 or not 0 <= v <= 20 for v in coordinates):
            raise ValueError('source no longer lies on exact twentieths grid')
        schemes[name] = {
            'points': [[int(v) for v in coordinates[i:i + 3]] for i in range(0, len(coordinates), 3)],
            **{key: initializer(body, key) for key in ['faces', 'polys', 'winding']},
        }
    if len(schemes) != 13:
        raise ValueError('expected thirteen pinned schemes')
    generated = '/*\n' + notice + '\n*/\n'
    generated += '// Generated by tools/import-cinolib-reference.py; primal polyhedra, NOT H8 tables.\n'
    generated += f'export const CINO_REFERENCE_COMMIT = "{COMMIT}";\n'
    generated += f'export const CINO_REFERENCE_SHA256 = "{SHA256}";\n'
    generated += 'export interface PrimalReferenceScheme { points: number[][]; faces: number[][]; polys: number[][]; winding: boolean[][] }\n'
    generated += 'export const CINO_PRIMAL_SCHEMES: Readonly<Record<string, PrimalReferenceScheme>> = ' + json.dumps(schemes, separators=(',', ':')) + ';\n'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generated, encoding='utf-8', newline='\n')
    print(json.dumps({'schemes': len(schemes), 'output': str(output), 'sourceCommit': COMMIT}))


if __name__ == '__main__':
    main()
